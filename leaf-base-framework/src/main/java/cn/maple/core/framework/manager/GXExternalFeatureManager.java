package cn.maple.core.framework.manager;

/**
 * 对接外部接口或第三方平台的标记接口
 * <p>
 * 该接口作为一个标记接口，用于标识需要与外部系统或第三方平台进行交互的功能组件。
 * 实现此接口的类应当遵循以下原则：
 * 1. 职责单一：每个实现类应当只负责与一个特定的外部系统或平台交互
 * 2. 异常处理：所有与外部系统的交互都应当有完善的异常处理机制
 * 3. 超时控制：应当设置合理的超时时间，避免因外部系统响应慢而影响本系统性能
 * 4. 日志记录：应当记录关键操作日志，特别是异常情况和重要的业务操作
 * 5. 重试机制：对于关键操作，应当实现合理的重试机制
 * 6. 配置外部化：与外部系统交互的配置信息应当外部化配置，便于环境切换
 * </p>
 *
 * <p>常见的实现场景包括但不限于：</p>
 * <ul>
 *   <li>微信支付、登录等接口集成</li>
 *   <li>支付宝支付、登录等接口集成</li>
 *   <li>短信服务提供商API集成</li>
 *   <li>第三方物流系统对接</li>
 *   <li>上游或下游业务系统的API调用</li>
 *   <li>第三方数据服务提供商的API调用</li>
 * </ul>
 *
 * @author 子曦
 */
public interface GXExternalFeatureManager {
    /**
     * 检查与外部系统的连接状态
     * 实现类可以重写此方法来提供连接状态检查功能
     *
     * @return 如果连接正常返回true，否则返回false
     */
    default boolean checkConnection() {
        return true;
    }
}
